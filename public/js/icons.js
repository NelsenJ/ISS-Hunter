/**
 * Membuat elemen span yang berisi ikon SVG vector.
 *
 * @param {keyof typeof ICONS} name
 * @param {number} [size=16]
 * @param {string} [extraClass='']
 * @returns {HTMLSpanElement}
 */
export function createIcon(name, size = 16, extraClass = '') {
  const span = document.createElement('span');
  span.className = `icon-wrap ${extraClass}`.trim();
  span.style.display = 'inline-flex';
  span.style.alignItems = 'center';
  span.style.justifyContent = 'center';
  span.style.width = `${size}px`;
  span.style.height = `${size}px`;
  span.style.flexShrink = '0';
  span.setAttribute('aria-hidden', 'true');

  const rawSvg = ICONS[name] || ICONS['help-circle'];
  span.innerHTML = rawSvg;

  const svgEl = span.querySelector('svg');
  if (svgEl) {
    svgEl.setAttribute('width', String(size));
    svgEl.setAttribute('height', String(size));
  }

  return span;
}
